interface MyApplication {
  id: string; reference: string; state: string; motivation: string; sharingConsent: boolean;
  submittedAt: string | null; decidedAt: string | null; withdrawnReason: string; version: number;
  programSlug: string; programTitle: string; operator: string;
  cohort: { id: string; name: string; startAt: string; endAt: string; timezone: string };
  interviews: Array<{ id: string; scheduledAt: string; durationMinutes: number; timezone: string; mode: string; location: string; state: string; version: number }>;
  enrollment: { id: string; state: string; invitationExpiresAt: string; confirmedAt: string | null; version: number; acceptable: boolean } | null;
  waitlistPosition: number | null;
  latestDecision: { outcome: string; reason: string; at: string } | null;
  trainingIsNotEmployment: boolean;
}

export function MyApplications({ locale, applicationId, mode }: { locale: Locale; applicationId?: string; mode: 'list' | 'new' | 'detail' | 'edit' }) {
  const L = (path: string) => localePath(locale, path);
  const t = translator(locale);
  const [rows, setRows] = useState<MyApplication[] | null>(null);
  const [detail, setDetail] = useState<(MyApplication & { program: { withdrawalPolicy: string; attendancePolicy: string; complaintsContact: string }; decisions: Array<{ id: string; outcome: string; reason: string; at: string }> }) | null>(null);
  const [program, setProgram] = useState<{ title: string; slug: string; acceptsApplications: boolean; applicationsUnavailableReason: string; cohorts: Array<{ id: string; name: string; startAt: string; seatsRemaining: number }> } | null>(null);
  const [draft, setDraft] = useState<MyApplication | null>(null);
  const [signedIn, setSignedIn] = useState(true);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');

  const load = useCallback(async () => {
    if (mode === 'list') { setRows(await api('/me/applications') as MyApplication[]); return; }
    if (mode === 'new') {
      const slug = new URLSearchParams(window.location.search).get('program');
      if (!slug) throw new Error('لم يُحدَّد البرنامج.');
      setProgram(await api(`/programs/${encodeURIComponent(slug)}`) as typeof program);
      return;
    }
    if (applicationId) setDetail(await api(`/me/applications/${applicationId}`) as typeof detail);
  }, [mode, applicationId]);

  useEffect(() => {
    let active = true;
    (async () => {
      try { await load(); }
      catch (e) {
        if (!active) return;
        if (e instanceof UnauthenticatedError) setSignedIn(false);
        else setError(e instanceof Error ? e.message : 'تعذر التحميل.');
      }
      finally { if (active) setLoading(false); }
    })();
    return () => { active = false; };
  }, [load]);

  const run = async (action: () => Promise<string>) => {
    if (busy) return;
    setBusy(true); setError(''); setNotice('');
    try { setNotice(await action()); await load(); }
    catch (e) { setError(e instanceof Error ? e.message : 'تعذر إكمال العملية.'); }
    finally { setBusy(false); }
  };

  const shell = (children: ReactNode) => (
    <AppShell locale={locale} path="/app/applications" signedIn={signedIn}
      userActions={<a className="tmk-button tmk-button--quiet" href={L('/app/applications')}>طلباتي</a>}>
      {error ? <Notice tone="danger" live="assertive">{error}</Notice> : null}
      {notice ? <Notice tone="success" live="polite">{notice}</Notice> : null}
      {children}
    </AppShell>
  );

  if (loading) return shell(<Skeleton lines={6} label={t('loading')} />);
  if (!signedIn) {
    return shell(
      <ErrorState title={t('forbiddenTitle')} onRetry={<a className="tmk-button tmk-button--primary" href={`${L('/login')}?returnTo=${encodeURIComponent(L('/app/applications'))}`}>{t('signIn')}</a>}>
        الطلب يُنسب إلى شخص بعينه، فيحتاج حسابًا.
      </ErrorState>
    );
  }

  // ---- PER-11: a new application ------------------------------------------------------------------
  if (mode === 'new') {
    if (!program) return shell(<ErrorState title="غير موجود">هذا البرنامج غير متاح للتقديم.</ErrorState>);
    return shell(
      <>
        <PageHeader dashboard eyebrow={program.title} title="طلب جديد" lead="احفظ مسودة ثم أرسلها. المسودة لا يراها أحد غيرك، ولا تُنشئ مقعدًا." />
        <NotEmployment />
        {!program.acceptsApplications ? (
          <Notice tone="warning" title="التقديم مغلق">
            <p style={{ marginBlockEnd: 0 }}>لم يعد هذا البرنامج يقبل طلبات ({program.applicationsUnavailableReason}).</p>
          </Notice>
        ) : draft ? (
          <Card title="المسودة محفوظة">
            <p>رقم طلبك: <code><Ltr>{draft.reference}</Ltr></code></p>
            <p className="tmk-row__actions">
              <a className="tmk-button tmk-button--primary" href={L(`/app/applications/${draft.id}/edit`)}>أكمل الطلب</a>
              <a className="tmk-button tmk-button--quiet" href={L('/app/applications')}>طلباتي</a>
            </p>
          </Card>
        ) : (
          <Card title="اختر الدفعة واكتب دافعك">
            <form onSubmit={event => {
              event.preventDefault();
              const form = new FormData(event.currentTarget);
              void run(async () => {
                const created = await api('/applications', 'POST', {
                  cohortId: String(form.get('cohortId') ?? ''),
                  motivation: String(form.get('motivation') ?? '')
                }) as MyApplication;
                setDraft(created);
                return 'حُفظت المسودة. لم تُرسل بعد، ولم يطّلع عليها أحد.';
              });
            }}>
              <div className="tmk-field">
                <label className="tmk-field__label" htmlFor="cohortId">الدفعة</label>
                <select id="cohortId" name="cohortId" className="tmk-field__control" required>
                  {program.cohorts.map(cohort => (
                    <option key={cohort.id} value={cohort.id}>
                      {cohort.name} — يبدأ {formatDate(cohort.startAt, locale)} · مقاعد متبقية {cohort.seatsRemaining}
                    </option>
                  ))}
                </select>
              </div>
              <div className="tmk-field">
                <label className="tmk-field__label" htmlFor="motivation">لماذا تتقدم لهذا البرنامج؟</label>
                <textarea id="motivation" name="motivation" className="tmk-field__control" rows={6} maxLength={4000} required />
              </div>
              <button type="submit" className="tmk-button tmk-button--primary" disabled={busy}>احفظ المسودة</button>
            </form>
          </Card>
        )}
      </>
    );
  }

  // ---- PER-11 edit / PER-12 detail ---------------------------------------------------------------
  if (mode === 'detail' || mode === 'edit') {
    if (!detail) return shell(<ErrorState title="غير موجود">هذا الطلب غير موجود ضمن سجلك.</ErrorState>);
    const state = applicationStates[detail.state] ?? { text: detail.state, tone: 'neutral' as Tone };
    return shell(
      <>
        <PageHeader
          dashboard
          eyebrow={`${detail.operator} · ${detail.programTitle}`}
          title={`طلب ${detail.reference}`}
          lead="كل خطوة على حدة: الإرسال، والفرز، والمقابلة، والقرار، ثم قبولك للمقعد."
          actions={<StatusBadge tone={state.tone}>{state.text}</StatusBadge>}
        />
        <NotEmployment />

        {/* PER-11.A03. What the reviewer actually receives, assembled from the same two pieces the
            server sends: the answers on this form, and the profile under its own consent. */}
        {detail.state === 'draft' ? (
          <Card title="معاينة ما سيستلمه المراجع">
            <p className="tmk-field__hint">
              يستلم المراجع شيئين فقط: نص دافعك أدناه، وملف مهاراتك إن وافقت على مشاركته. لا يصله شيء آخر من حسابك.
            </p>
            <dl className="tmk-definitions">
              <div><dt>رقم الطلب</dt><dd><code><Ltr>{detail.reference}</Ltr></code></dd></div>
              <div><dt>الدفعة</dt><dd>{detail.cohort.name}</dd></div>
              <div><dt>دافع التقديم</dt><dd>{detail.motivation || <span className="tmk-field__hint">لم يُكتب بعد</span>}</dd></div>
            </dl>
            <p className="tmk-row__actions">
              <a className="tmk-button tmk-button--quiet" href={L('/app/career/profile')}>اعرض ملفك كما تراه الجهة</a>
            </p>
          </Card>
        ) : null}

        {detail.state === 'draft' ? (
          <Card title="أكمل الطلب وأرسله">
            <form onSubmit={event => {
              event.preventDefault();
              const form = new FormData(event.currentTarget);
              const consent = form.get('sharingConsent') === 'on';
              void run(async () => {
                // Named before the request, so the answer is the one thing that is missing rather
                // than a general list of everything this endpoint can refuse.
                if (!consent) throw new Error('الموافقة على مشاركة ملفك شرط للإرسال: بدونها لا تستطيع الجهة تقييم طلبك أصلًا.');
                await api('/applications', 'POST', { cohortId: detail.cohort.id, applicationId: detail.id, motivation: String(form.get('motivation') ?? ''), version: detail.version });
                const refreshed = await api(`/me/applications/${detail.id}`) as typeof detail;
                await api(`/applications/${detail.id}/submit`, 'POST', { sharingConsent: consent, version: refreshed!.version });
                return `أُرسل الطلب برقم ${detail.reference}. الموعد النهائي يُفحص لحظة الإرسال، وقد وصل قبله.`;
              });
            }}>
              <div className="tmk-field">
                <label className="tmk-field__label" htmlFor="motivation">لماذا تتقدم لهذا البرنامج؟</label>
                <textarea id="motivation" name="motivation" className="tmk-field__control" rows={6} defaultValue={detail.motivation} maxLength={4000} required />
              </div>
              <label className="tmk-choice" htmlFor="sharingConsent">
                <input id="sharingConsent" name="sharingConsent" type="checkbox" />
                <span>أوافق على مشاركة ملف مهاراتي مع هذه الجهة المشغّلة لغرض هذا الطلب.</span>
              </label>
              <p className="tmk-field__hint">
                بدون هذه الموافقة لا يمكن تقييم طلبك أصلًا، فهي شرط للإرسال لا خيار بعده. يمكنك سحبها لاحقًا من ملف المهارات.
              </p>
              <p className="tmk-row__actions">
                <button type="submit" className="tmk-button tmk-button--primary" disabled={busy}>أرسل الطلب</button>
                <button type="button" className="tmk-button tmk-button--quiet" disabled={busy}
                  onClick={() => void run(async () => {
                    await api(`/applications/${detail.id}/discard`, 'POST', { version: detail.version });
                    return 'أُلغيت المسودة. لم يرها أحد.';
                  })}>
                  ألغِ المسودة
                </button>
              </p>
            </form>
          </Card>
        ) : null}

        <Card title="مسار الطلب">
          <dl className="tmk-definitions">
            <div><dt>الدفعة</dt><dd>{detail.cohort.name} — {formatDate(detail.cohort.startAt, locale)} (<Ltr>{detail.cohort.timezone}</Ltr>)</dd></div>
            <div><dt>أُرسل</dt><dd>{detail.submittedAt ? formatDate(detail.submittedAt, locale, true) : '—'}</dd></div>
            <div><dt>القرار</dt><dd>{detail.decidedAt ? formatDate(detail.decidedAt, locale, true) : <span className="tmk-field__hint">لم يصدر بعد</span>}</dd></div>
            {detail.waitlistPosition ? <div><dt>موقعك في قائمة الانتظار</dt><dd><Ltr>{String(detail.waitlistPosition)}</Ltr></dd></div> : null}
          </dl>
          {detail.decisions.length > 0 ? (
            <ul>
              {detail.decisions.map(decision => (
                <li key={decision.id}>
                  <strong>{applicationStates[decision.outcome]?.text ?? decision.outcome}</strong>
                  {decision.reason ? ` — ${decision.reason}` : ''} <span className="tmk-field__hint">{formatDate(decision.at, locale)}</span>
                </li>
              ))}
            </ul>
          ) : null}
        </Card>

        {detail.interviews.length > 0 ? (
          <Card title="المقابلات">
            {detail.interviews.map(interview => (
              <article className="tmk-row" key={interview.id}>
                <div>
                  <strong>{formatDate(interview.scheduledAt, locale, true)}</strong>
                  <p className="tmk-field__hint">
                    <Ltr>{interview.timezone}</Ltr> · {interview.durationMinutes} دقيقة · {interview.mode === 'remote' ? 'عن بعد' : interview.location}
                  </p>
                  <p className="tmk-field__hint">
                    <StatusBadge tone={interviewStates[interview.state]?.tone ?? 'neutral'}>
                      {interviewStates[interview.state]?.text ?? interview.state}
                    </StatusBadge>
                  </p>
                </div>
                <span className="tmk-row__actions">
                  {['proposed', 'reschedule_requested'].includes(interview.state) ? (
                    <button type="button" className="tmk-button tmk-button--primary" disabled={busy}
                      onClick={() => void run(async () => {
                        await api(`/interviews/${interview.id}/confirm`, 'POST', { version: interview.version });
                        return 'أكّدت الموعد.';
                      })}>
                      أكّد الموعد
                    </button>
                  ) : null}
                  {interview.state !== 'cancelled' ? (
                    <button type="button" className="tmk-button tmk-button--quiet" disabled={busy}
                      onClick={() => void run(async () => {
                        const why = window.prompt('سبب طلب تغيير الموعد (عشرة أحرف على الأقل):') ?? '';
                        if (why.trim().length < 10) throw new Error('السبب مطلوب ولا يقل عن عشرة أحرف.');
                        const alternatives = window.prompt('بدائل تناسبك (اختياري):') ?? '';
                        await api(`/interviews/${interview.id}/reschedule-requests`, 'POST', { reason: why, alternatives });
                        return 'أُرسل طلب تغيير الموعد. الموعد الأصلي ما زال قائمًا حتى ترد الجهة، فلا تعتبره ملغى.';
                      })}>
                      اطلب تغيير الموعد
                    </button>
                  ) : null}
                </span>
              </article>
            ))}
            <p className="tmk-field__hint">
              كل موعد يحمل منطقته الزمنية. طلب التغيير طلب لا تعديل: الموعد لا يتحرك قبل رد الجهة.
            </p>
          </Card>
        ) : null}

        {detail.enrollment ? (
          <Card title="المقعد">
            <div className="tmk-grid tmk-grid--stats">
              <Stat label="الحالة" value={enrollmentStates[detail.enrollment.state]?.text ?? detail.enrollment.state} />
              <Stat label="تنتهي المهلة" value={formatDate(detail.enrollment.invitationExpiresAt, locale, true)} note="بعدها يتحرر المقعد للتالي في قائمة الانتظار." />
            </div>
            {detail.enrollment.acceptable ? (
              <p className="tmk-row__actions">
                <button type="button" className="tmk-button tmk-button--primary" disabled={busy}
                  onClick={() => void run(async () => {
                    await api(`/enrollments/${detail.enrollment!.id}/accept`, 'POST', { version: detail.enrollment!.version });
                    return 'قبلت المقعد. هذا التحاق بتدريب، وليس عقد عمل.';
                  })}>
                  اقبل المقعد
                </button>
              </p>
            ) : detail.enrollment.state === 'invited' ? (
              <Notice tone="warning" title="انتهت المهلة">
                <p style={{ marginBlockEnd: 0 }}>مضت مهلة قبول المقعد، فتحرر لغيرك. لا يمكن قبوله متأخرًا.</p>
              </Notice>
            ) : null}
            {detail.enrollment.state === 'confirmed' || detail.enrollment.state === 'active' ? (
              <p className="tmk-row__actions">
                <a className="tmk-button tmk-button--secondary" href={L(`/app/training/${detail.enrollment.id}`)}>افتح تدريبي</a>
              </p>
            ) : null}
          </Card>
        ) : null}

        {['submitted', 'screening', 'shortlisted', 'interview', 'waitlisted', 'accepted'].includes(detail.state) ? (
          <Card title="سحب الطلب">
            <p className="tmk-field__hint">السحب يحرر المقعد أو الدور إن كان محجوزًا، ويبقي أثر ما حدث في سجلك.</p>
            <button type="button" className="tmk-button tmk-button--quiet" disabled={busy}
              onClick={() => void run(async () => {
                const why = window.prompt('سبب السحب (عشرة أحرف على الأقل):') ?? '';
                if (why.trim().length < 10) throw new Error('السبب مطلوب ولا يقل عن عشرة أحرف.');
                await api(`/applications/${detail.id}/withdraw`, 'POST', { reason: why, version: detail.version });
                return 'سُحب الطلب وتحرر ما كان محجوزًا.';
              })}>
              اسحب الطلب
            </button>
          </Card>
        ) : null}

        <Card title="سياسات تخصك">
          <div className="tmk-prose">
            <h3>الانسحاب</h3><p>{detail.program.withdrawalPolicy}</p>
            <h3>الحضور</h3><p>{detail.program.attendancePolicy}</p>
          </div>
          {detail.program.complaintsContact ? <p className="tmk-field__hint">مسؤول الشكاوى: <bdi>{detail.program.complaintsContact}</bdi></p> : null}
        </Card>
      </>
    );
  }

  // ---- PER-12: the list ---------------------------------------------------------------------------
  return shell(
    <>
      <PageHeader dashboard title="طلباتي" lead="كل طلب وحالته الحقيقية: المسودة ليست إرسالًا، والقبول ليس مقعدًا حتى تقبله، والمقعد ليس وظيفة." />
      <NotEmployment />
      <Card title="الطلبات">
        <DataTable
          caption="طلباتك، أحدثها أولًا"
          rows={rows ?? []}
          rowKey={row => row.id}
          emptyState={
            <EmptyState title="لا طلبات بعد" action={<a className="tmk-button tmk-button--primary" href={L('/opportunities')}>اكتشف البرامج</a>}>
              لم تتقدم لأي برنامج حتى الآن. حفظ برنامج في قائمتك لا يُنشئ طلبًا.
            </EmptyState>
          }
          columns={[
            { key: 'program', header: 'البرنامج', cell: row => <><a href={L(`/programs/${row.programSlug}`)}>{row.programTitle}</a><span className="tmk-field__hint">{row.operator}</span></> },
            { key: 'reference', header: 'الرقم', cell: row => <code><Ltr>{row.reference}</Ltr></code> },
            { key: 'cohort', header: 'الدفعة', cell: row => row.cohort.name },
            { key: 'state', header: 'الحالة', cell: row => <StatusBadge tone={applicationStates[row.state]?.tone ?? 'neutral'}>{applicationStates[row.state]?.text ?? row.state}</StatusBadge> },
            {
              key: 'seat', header: 'المقعد',
              cell: row => row.enrollment
                ? <>{enrollmentStates[row.enrollment.state]?.text ?? row.enrollment.state}{row.enrollment.acceptable ? <span className="tmk-field__hint">تنتهي المهلة {formatDate(row.enrollment.invitationExpiresAt, locale, true)}</span> : null}</>
                : row.waitlistPosition ? <>قائمة انتظار — الدور <Ltr>{String(row.waitlistPosition)}</Ltr></> : <span className="tmk-field__hint">—</span>
            },
            { key: 'open', header: '', cell: row => <a href={L(`/app/applications/${row.id}`)}>{row.state === 'draft' ? 'أكمل' : 'افتح'}</a> }
          ]}
        />
      </Card>
    </>
  );
}

