/**
 * PART-10 screens: PER-10 the skills profile, PER-11/12 applying and following an application,
 * PER-13 a trainee's own training, PRG-01..05 the operator's side, and the independent review.
 *
 * What these screens must get right, because getting it wrong misleads somebody about their future:
 *
 *  - **Training is not employment.** No screen implies a job, and the ones a candidate reads say so
 *    in words at the moment they would otherwise assume it.
 *  - **A seat is invited, then accepted, then held.** Three different things, never one badge.
 *  - **Nothing about a person leaves their account without their say-so**, and the preview showing
 *    what an operator receives is generated by the server from the same allowlist the operator reads.
 *  - **An attendance record can decide whether somebody is paid**, so a change is a revision with a
 *    reason, and a dispute goes to somebody who did not make the record.
 */

class UnauthenticatedError extends Error {}

const api = async (path: string, method: 'GET' | 'POST' | 'PATCH' | 'PUT' = 'GET', body?: unknown) => {
  const response = await fetch(`/api/v1${path}`, {
    method, credentials: 'include',
    headers: body ? { 'content-type': 'application/json' } : {},
    ...(body ? { body: JSON.stringify(body) } : {})
  });
  const payload = await response.json().catch(() => ({}));
  if (response.status === 401) throw new UnauthenticatedError('unauthenticated');
  if (!response.ok) throw new Error(message(payload?.error?.code, response.status));
  return payload.data;
};

function message(code: string | undefined, status: number): string {
  const messages: Record<string, string> = {
    forbidden: 'لا تملك صلاحية هذا الإجراء ضمن هذه الدفعة أو هذا البرنامج.',
    not_found: 'المورد غير موجود ضمن نطاقك.',
    conflict: 'تغيّرت الحالة: قد يكون الموعد النهائي مضى، أو امتلأت المقاعد، أو انتهت مهلة قبول المقعد، أو النسخة التي بين يديك قديمة. أعد التحميل واقرأ ما تغيّر.',
    // Written for the person reading these screens — a candidate — not for an operator. The
    // operator's screens carry their own wording for the same code.
    invalid_input: 'تحقق من الحقول: اكتب دافعك للتقديم، ووافق على مشاركة ملفك، واملأ ملف المهارات قبل الإرسال.'
  };
  return messages[code ?? ''] ?? `تعذر إكمال العملية (${status}).`;
}

