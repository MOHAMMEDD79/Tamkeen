interface CandidateProfile {
  exists: boolean; headline: string; summary: string; city: string; availability: string;
  education: string; experience: string; skills: string[]; cvReference: string;
  cvUploadAvailable: boolean; shareWithOperators: boolean; shareContact: boolean; version: number;
}

export function CareerProfile({ locale }: { locale: Locale }) {
  const L = (path: string) => localePath(locale, path);
  const t = translator(locale);
  const [profile, setProfile] = useState<CandidateProfile | null>(null);
  const [preview, setPreview] = useState<{ shared: boolean; withheld: string[]; profile: Record<string, unknown> } | null>(null);
  const [signedIn, setSignedIn] = useState(true);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');

  const load = useCallback(async () => setProfile(await api('/me/candidate-profile') as CandidateProfile), []);

  useEffect(() => {
    let active = true;
    (async () => {
      try { await load(); }
      catch (e) {
        if (!active) return;
        if (e instanceof UnauthenticatedError) setSignedIn(false);
        else setError(e instanceof Error ? e.message : 'تعذر تحميل الملف.');
      }
      finally { if (active) setLoading(false); }
    })();
    return () => { active = false; };
  }, [load]);

  const save = async (event: FormEvent<HTMLFormElement>) => {
    event.preventDefault();
    if (busy || !profile) return;
    const form = new FormData(event.currentTarget);
    setBusy(true); setError(''); setNotice('');
    try {
      const skills = String(form.get('skills') ?? '').split(/[,،]/).map(skill => skill.trim()).filter(Boolean);
      await api('/me/candidate-profile', 'PATCH', {
        headline: String(form.get('headline') ?? ''),
        summary: String(form.get('summary') ?? ''),
        city: String(form.get('city') ?? ''),
        availability: String(form.get('availability') ?? ''),
        education: String(form.get('education') ?? ''),
        experience: String(form.get('experience') ?? ''),
        cvReference: String(form.get('cvReference') ?? ''),
        skills,
        shareWithOperators: form.get('shareWithOperators') === 'on',
        shareContact: form.get('shareContact') === 'on',
        ...(profile.exists ? { version: profile.version } : {})
      });
      await load();
      setPreview(null);
      setNotice('حُفظ الملف. تسري الموافقة على المشاركة فورًا، وسحبها يخفيه عن كل جهة مشغّلة في الحال.');
    } catch (e) {
      setError(e instanceof Error ? e.message : 'تعذر حفظ الملف.');
    } finally { setBusy(false); }
  };

  const shell = (children: ReactNode) => (
    <AppShell locale={locale} path="/app/career/profile" signedIn={signedIn}
      userActions={<a className="tmk-button tmk-button--quiet" href={L('/app')}>{t('personalWorkspace')}</a>}>
      {error ? <Notice tone="danger" live="assertive">{error}</Notice> : null}
      {notice ? <Notice tone="success" live="polite">{notice}</Notice> : null}
      {children}
    </AppShell>
  );

  if (loading) return shell(<Skeleton lines={6} label={t('loading')} />);
  if (!signedIn) {
    return shell(
      <ErrorState title={t('forbiddenTitle')} onRetry={<a className="tmk-button tmk-button--primary" href={`${L('/login')}?returnTo=${encodeURIComponent(L('/app/career/profile'))}`}>{t('signIn')}</a>}>
        {t('forbiddenBody')}
      </ErrorState>
    );
  }
  if (!profile) return shell(<ErrorState title="تعذر التحميل">أعد المحاولة.</ErrorState>);

  return shell(
    <>
      <PageHeader
        dashboard
        title="ملف المهارات"
        lead="هذا ما قد تختار مشاركته مع جهة مشغّلة عند التقديم. لا يغادر حسابك شيء منه قبل أن توافق، والموافقة قابلة للسحب في أي وقت."
      />

      <Card title="الملف">
        <form onSubmit={event => void save(event)}>
          <div className="tmk-field">
            <label className="tmk-field__label" htmlFor="headline">سطر التعريف</label>
            <input id="headline" name="headline" className="tmk-field__control" defaultValue={profile.headline} maxLength={200} />
          </div>
          <div className="tmk-field">
            <label className="tmk-field__label" htmlFor="summary">نبذة</label>
            <textarea id="summary" name="summary" className="tmk-field__control" rows={4} defaultValue={profile.summary} maxLength={2000} />
          </div>
          <div className="tmk-grid tmk-grid--stats">
            <div className="tmk-field">
              <label className="tmk-field__label" htmlFor="city">المدينة</label>
              <input id="city" name="city" className="tmk-field__control" defaultValue={profile.city} maxLength={100} />
            </div>
            <div className="tmk-field">
              <label className="tmk-field__label" htmlFor="availability">التوفر</label>
              <span className="tmk-field__hint" id="availability-hint">مثل: مساءً، أو ابتداءً من أيار.</span>
              <input id="availability" name="availability" className="tmk-field__control" defaultValue={profile.availability} maxLength={200} aria-describedby="availability-hint" />
            </div>
          </div>
          <div className="tmk-field">
            <label className="tmk-field__label" htmlFor="skills">المهارات</label>
            <span className="tmk-field__hint" id="skills-hint">افصل بينها بفاصلة. هذه ما تُفلتر عليه البرامج.</span>
            <input id="skills" name="skills" className="tmk-field__control" defaultValue={profile.skills.join('، ')} aria-describedby="skills-hint" />
          </div>
          <div className="tmk-field">
            <label className="tmk-field__label" htmlFor="education">التعليم</label>
            <textarea id="education" name="education" className="tmk-field__control" rows={3} defaultValue={profile.education} maxLength={1000} />
          </div>
          <div className="tmk-field">
            <label className="tmk-field__label" htmlFor="experience">الخبرة</label>
            <textarea id="experience" name="experience" className="tmk-field__control" rows={4} defaultValue={profile.experience} maxLength={2000} />
          </div>
          <div className="tmk-field">
            <label className="tmk-field__label" htmlFor="cvReference">مرجع السيرة الذاتية</label>
            <span className="tmk-field__hint" id="cv-hint">
              رفع الملفات لم يُبنَ بعد (PER-10.A02): اكتب هنا اسم المستند أو رابطه لدى جهة أخرى، ولا يُرفع شيء إلى المنصة.
            </span>
            <input id="cvReference" name="cvReference" className="tmk-field__control" defaultValue={profile.cvReference} maxLength={200} aria-describedby="cv-hint" />
          </div>

          <fieldset className="tmk-fieldset">
            <legend>المشاركة</legend>
            <label className="tmk-choice" htmlFor="shareWithOperators">
              <input id="shareWithOperators" name="shareWithOperators" type="checkbox" defaultChecked={profile.shareWithOperators} />
              <span>أوافق على مشاركة هذا الملف مع الجهة المشغّلة للبرامج التي أتقدم إليها.</span>
            </label>
            <label className="tmk-choice" htmlFor="shareContact">
              <input id="shareContact" name="shareContact" type="checkbox" defaultChecked={profile.shareContact} />
              <span>أوافق أيضًا على مشاركة بريدي الإلكتروني معها.</span>
            </label>
            <p className="tmk-field__hint">
              الموافقتان منفصلتان، والثانية لا تسري بدون الأولى. سحب الأولى يخفي الملف عن كل جهة فورًا، بما فيها طلبات قائمة.
            </p>
          </fieldset>

          <p className="tmk-row__actions">
            <button type="submit" className="tmk-button tmk-button--primary" disabled={busy}>احفظ الملف</button>
            <button type="button" className="tmk-button tmk-button--secondary" disabled={busy}
              onClick={() => void (async () => {
                setBusy(true); setError('');
                try { setPreview(await api('/me/candidate-profile/employer-preview') as typeof preview); }
                catch (e) { setError(e instanceof Error ? e.message : 'تعذر عرض المعاينة.'); }
                finally { setBusy(false); }
              })()}>
              ماذا ترى الجهة المشغّلة؟
            </button>
          </p>
        </form>
      </Card>

      {/* PER-10.A03. Generated by the server from the same allowlist the operator reads.
          The heading changes with the consent, because a list of fields under the words "this is
          what they receive" is false while the consent is off — and a candidate deciding whether
          to turn it on still needs to see what turning it on would send. */}
      {preview ? (
        <Card title={preview.shared ? 'ما تستلمه الجهة المشغّلة الآن' : 'ما ستشاركه إن وافقت'}>
          <p className="tmk-field__hint">
            {preview.shared
              ? 'هذه ليست محاكاة: الخادم يبنيها بالدالة نفسها التي تبني قراءة الجهة، فما تراه هنا هو ما تستلمه هي بالضبط.'
              : 'الخادم يبنيها بالدالة نفسها التي تبني قراءة الجهة، فهذه هي الحقول التي ستخرج من حسابك لو فعّلت الموافقة — ولا تخرج الآن.'}
          </p>
          {!preview.shared ? (
            <Notice tone="warning" title="لا تُشارك شيئًا الآن">
              <p style={{ marginBlockEnd: 0 }}>
                لم توافق على المشاركة، فلا ترى الجهة المشغّلة أي جزء من ملفك. ما يظهر أدناه معاينة لما سيخرج لو وافقت، لا لما خرج.
              </p>
            </Notice>
          ) : null}
          <dl className="tmk-definitions">
            {Object.entries(preview.profile).map(([key, value]) => (
              <div key={key}>
                <dt>{key}</dt>
                <dd>{value === null ? <span className="tmk-field__hint">محجوب</span> : Array.isArray(value) ? value.join('، ') : String(value)}</dd>
              </div>
            ))}
          </dl>
          <p className="tmk-field__hint">
            لا يُرسل أبدًا: {preview.withheld.join('، ')}. هذه ليست حقولًا فارغة، بل حقول لا تخرج من حسابك أصلًا.
          </p>
        </Card>
      ) : null}

      <p className="tmk-row__actions">
        <a className="tmk-button tmk-button--secondary" href={L('/opportunities')}>اكتشف البرامج</a>
        <a className="tmk-button tmk-button--quiet" href={L('/app/applications')}>طلباتي</a>
      </p>
    </>
  );
}

