interface MyTrainingData {
  enrollment: { id: string; state: string; confirmedAt: string | null; exitReason: string; version: number };
  cohort: { id: string; name: string; startAt: string; endAt: string; timezone: string };
  program: { id: string; title: string; slug: string; attendancePolicy: string; assessmentPolicy: string; withdrawalPolicy: string; complaintsContact: string; operator: string };
  sessions: Array<{
    id: string; title: string; startsAt: string; endsAt: string; timezone: string; location: string; state: string;
    attendance: { id: string; status: string; excuseNote: string; recordedAt: string } | null;
    objection: { id: string; state: string; reason: string; decisionReason: string } | null;
    canObject: boolean;
  }>;
  attendanceSummary: { recorded: number; counted: number; present: number; late: number; excused: number; absent: number; policy: string };
  results: Array<{ id: string; title: string; total: number; scaleMax: number; passMark: number; passed: boolean; at: string }>;
  withdrawalRequests: Array<{ id: string; reason: string; state: string; decisionReason: string; createdAt: string }>;
  stipends: { available: boolean; reason: string; offeredByProgram: boolean; conditions: string };
  certificate: { available: boolean; reason: string };
}

export function MyTrainingScreen({ locale, enrollmentId }: { locale: Locale; enrollmentId: string }) {
  const L = (path: string) => localePath(locale, path);
  const t = translator(locale);
  const [data, setData] = useState<MyTrainingData | null>(null);
  const [signedIn, setSignedIn] = useState(true);
  const [loading, setLoading] = useState(true);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [notice, setNotice] = useState('');

  const load = useCallback(async () => setData(await api(`/me/training/${enrollmentId}`) as MyTrainingData), [enrollmentId]);

  useEffect(() => {
    let active = true;
    (async () => {
      try { await load(); }
      catch (e) {
        if (!active) return;
        if (e instanceof UnauthenticatedError) setSignedIn(false);
        else setError(e instanceof Error ? e.message : 'تعذر تحميل التدريب.');
      }
      finally { if (active) setLoading(false); }
    })();
    return () => { active = false; };
  }, [load]);

  const run = async (action: () => Promise<string>) => {
    if (busy) return;
    setBusy(true); setError(''); setNotice('');
    try { setNotice(await action()); await load(); }
    catch (e) { setError(e instanceof Error ? e.message : 'تعذر إكمال العملية.'); }
    finally { setBusy(false); }
  };

  const shell = (children: ReactNode) => (
    <AppShell locale={locale} path="/app/applications" signedIn={signedIn}
      userActions={<a className="tmk-button tmk-button--quiet" href={L('/app/applications')}>طلباتي</a>}>
      {error ? <Notice tone="danger" live="assertive">{error}</Notice> : null}
      {notice ? <Notice tone="success" live="polite">{notice}</Notice> : null}
      {children}
    </AppShell>
  );

  if (loading) return shell(<Skeleton lines={6} label={t('loading')} />);
  if (!signedIn) return shell(<ErrorState title={t('forbiddenTitle')} onRetry={<a className="tmk-button tmk-button--primary" href={L('/login')}>{t('signIn')}</a>}>{t('forbiddenBody')}</ErrorState>);
  if (!data) return shell(<ErrorState title="غير موجود">هذا التدريب غير موجود ضمن سجلك.</ErrorState>);

  return shell(
    <>
      <PageHeader
        dashboard
        eyebrow={`${data.program.operator} · ${data.cohort.name}`}
        title={data.program.title}
        lead="جدولك وسجل حضورك ونتائجك، وبجوارها القاعدة التي ستُقرأ بها."
        actions={<StatusBadge tone={enrollmentStates[data.enrollment.state]?.tone ?? 'neutral'}>{enrollmentStates[data.enrollment.state]?.text ?? data.enrollment.state}</StatusBadge>}
      />
      <NotEmployment />

      <div className="tmk-grid tmk-grid--stats">
        <Stat label="جلسات مسجَّلة" value={<Ltr>{String(data.attendanceSummary.recorded)}</Ltr>} />
        <Stat label="محتسبة لك" value={<Ltr>{String(data.attendanceSummary.counted)}</Ltr>} note="حضور أو تأخر أو غياب بعذر." />
        <Stat label="غياب بلا عذر" value={<Ltr>{String(data.attendanceSummary.absent)}</Ltr>} />
      </div>
      <Notice tone="info" title="القاعدة التي تُقرأ بها هذه الأرقام">
        <p style={{ marginBlockEnd: 0 }}>{data.attendanceSummary.policy}</p>
      </Notice>

      <Card title="الجلسات">
        <DataTable
          caption="جلسات دفعتك"
          rows={data.sessions}
          rowKey={session => session.id}
          emptyState={<EmptyState title="لا جلسات بعد">لم تُجدول جلسات لهذه الدفعة حتى الآن.</EmptyState>}
          columns={[
            { key: 'title', header: 'الجلسة', cell: session => <>{session.title}<span className="tmk-field__hint">{session.location}</span></> },
            { key: 'when', header: 'الموعد', cell: session => <>{formatDate(session.startsAt, locale, true)}<span className="tmk-field__hint"><Ltr>{session.timezone}</Ltr></span></> },
            {
              key: 'attendance', header: 'حضورك',
              cell: session => session.attendance
                ? <>
                    <StatusBadge tone={attendanceLabels[session.attendance.status]?.tone ?? 'neutral'}>{attendanceLabels[session.attendance.status]?.text ?? session.attendance.status}</StatusBadge>
                    {session.attendance.excuseNote ? <span className="tmk-field__hint">{session.attendance.excuseNote}</span> : null}
                  </>
                : <span className="tmk-field__hint">لم يُسجَّل</span>
            },
            {
              key: 'objection', header: 'الاعتراض',
              cell: session => session.objection
                ? <>{session.objection.state === 'open' ? 'قيد المراجعة' : session.objection.state === 'upheld' ? 'قُبل الاعتراض' : 'رُفض الاعتراض'}
                    {session.objection.decisionReason ? <span className="tmk-field__hint">{session.objection.decisionReason}</span> : null}</>
                : session.canObject
                  ? <button type="button" className="tmk-button tmk-button--quiet" disabled={busy}
                      onClick={() => void run(async () => {
                        const why = window.prompt('سبب الاعتراض (عشرة أحرف على الأقل):') ?? '';
                        if (why.trim().length < 10) throw new Error('السبب مطلوب ولا يقل عن عشرة أحرف.');
                        await api(`/attendance/${session.attendance!.id}/objections`, 'POST', { reason: why });
                        return 'سُجِّل اعتراضك. السجل لا يتغير قبل أن يبتّ فيه شخص غير من سجّله.';
                      })}>
                      اعترض
                    </button>
                  : <span className="tmk-field__hint">—</span>
            }
          ]}
        />
        <p className="tmk-field__hint">
          الاعتراض لا يعدّل السجل بنفسه. يراجعه شخص آخر غير من سجّله، وإن قُبل يُصحَّح بمراجعة مكتوبة تبقى في السجل.
        </p>
      </Card>

      {data.results.length > 0 ? (
        <Card title="نتائج التقييم">
          <DataTable
            caption="نتائجك"
            rows={data.results}
            rowKey={result => result.id}
            emptyState={<EmptyState title="لا نتائج" />}
            columns={[
              { key: 'title', header: 'التقييم', cell: result => result.title },
              { key: 'total', header: 'الدرجة', numeric: true, cell: result => <Ltr>{String(result.total)}</Ltr> },
              { key: 'pass', header: 'النتيجة', cell: result => <StatusBadge tone={result.passed ? 'success' : 'danger'}>{result.passed ? 'اجتياز' : 'دون حد الاجتياز'}</StatusBadge> },
              { key: 'at', header: 'التاريخ', cell: result => formatDate(result.at, locale) }
            ]}
          />
        </Card>
      ) : null}

      <Card title="الانسحاب">
        <div className="tmk-prose"><p>{data.program.withdrawalPolicy}</p></div>
        {data.withdrawalRequests.length > 0 ? (
          <ul>
            {data.withdrawalRequests.map(request => (
              <li key={request.id}>
                {request.state === 'open' ? 'قيد التقييم' : request.state === 'upheld' ? 'قُبل' : 'رُفض'} — {request.reason}
                {request.decisionReason ? <span className="tmk-field__hint">{request.decisionReason}</span> : null}
              </li>
            ))}
          </ul>
        ) : null}
        {['confirmed', 'active'].includes(data.enrollment.state) && !data.withdrawalRequests.some(request => request.state === 'open') ? (
          <button type="button" className="tmk-button tmk-button--quiet" disabled={busy}
            onClick={() => void run(async () => {
              const why = window.prompt('سبب طلب الانسحاب (عشرة أحرف على الأقل):') ?? '';
              if (why.trim().length < 10) throw new Error('السبب مطلوب ولا يقل عن عشرة أحرف.');
              await api(`/enrollments/${enrollmentId}/withdrawal-requests`, 'POST', { reason: why });
              return 'أُرسل طلب الانسحاب. لم يتغير التحاقك بعد: الجهة تقيّمه وفق السياسة المعلنة أعلاه.';
            })}>
            اطلب الانسحاب
          </button>
        ) : null}
      </Card>

      {/* PER-13.A03/A04: declared, not offered. */}
      <Card title="ما لا تستطيع هذه الصفحة فعله بعد">
        <ul>
          <li>
            <strong>البدلات.</strong> {data.stipends.offeredByProgram ? `يعلن البرنامج بدلًا (${data.stipends.conditions || 'بشروطه المعلنة'})، ` : 'لا يعلن هذا البرنامج بدلًا، و'}
            احتساب الاستحقاق وصرفه لم يُبنَ بعد، فلا يُعرض رقم استحقاق قد يُقرأ كوعد.
          </li>
          <li>
            <strong>الشهادة.</strong> إصدار الشهادات ومرجع تحققها العام لم يُبنَ بعد، فلا يوجد زر تنزيل.
          </li>
        </ul>
      </Card>
    </>
  );
}
